'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const {EventEmitter} = require('node:events');
const {PassThrough, Readable} = require('node:stream');
const {createSetup} = require('../src/setup');
const delay = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const root = fs.mkdtempSync(path.join(process.cwd(), '.setup-test-'));
  const config = {modelEndpoint:'http://127.0.0.1:11434/v1/chat/completions', modelApiKey:'secret-key', modelName:'test', groupAllowlist:[], bridgeToken:'', botUserId:'old'};
  const children = [];
  function spawn(file, args, opts) {
    const p = new EventEmitter();
    p.pid = 100 + children.length; p.stdout = new PassThrough(); p.stderr = new PassThrough();
    p.kill = () => { p.killed = true; if (!p.delayClose) process.nextTick(() => p.emit('close', 1)); };
    p.stdin = new PassThrough();
    p.stdin.on('data', chunk => {
      const input = JSON.parse(chunk.toString());
      const result = input.action === 'accounts' ? {accounts:[{account:'wxid_a_abcd',wxid:'wxid_a',dbDir:'db',label:'账号鲸鱼'},{account:'wxid_鲸_abcd',wxid:'wxid_鲸',dbDir:'db2',label:'中文账号'}]} : {account:input.account,wxid:'wxid_a',dbDir:'db',groups:[{id:'g@chatroom',name:'中文群聊'}],truncated:false};
      const bytes = Buffer.from(JSON.stringify(result));
      for (const byte of bytes) p.stdout.write(Buffer.from([byte]));
      p.stdout.end(); process.nextTick(() => p.emit('close',0));
    });
    p.stdin.on('finish', () => {
      if (opts.env.GAL_BRIDGE_MANAGED && !p.delayClose && !p.ignoreEOF) process.nextTick(() => p.emit('close',0));
    });
    p.options=opts; children.push(p); return p;
  }
  const setup = createSetup(root,config,{updateConfig:async fn => fn()},{spawn,startupTimeout:200,pollInterval:5,stopTimeout:20,instance:'owned-instance'});
  const original = global.fetch;
  try {
    assert(!JSON.stringify(setup.status()).includes('secret-key'));
    assert.equal(setup.status().instance,'owned-instance');
    assert.equal(setup.status().wechat.enableAccessibility,false,'accessibility must require explicit opt-in');
    assert.equal(setup.status().game.randomEventsEnabled,true);
    await assert.rejects(setup.action('save',{account:'forged',groupIds:['fake@chatroom']}));
    let sent;
    global.fetch = async (url, options) => { sent = {url,options}; return {ok:true,body:Readable.from([JSON.stringify({choices:[{message:{content:JSON.stringify({reply:'hi',delta:0,reason:'ok'})}}]})])}; };
    assert.equal((await setup.action('test-model',{endpoint:config.modelEndpoint,name:'test'})).ok,true);
    assert.equal(sent.options.headers.authorization,'Bearer secret-key');
    await assert.rejects(setup.action('test-model',{endpoint:'http://localhost:1234/v1',name:'test'}));
    assert.equal((await setup.action('test-model',{endpoint:'http://localhost:1234/v1',name:'test',clearKey:true})).ok,true);
    assert.equal(sent.options.headers.authorization,undefined);
    global.fetch = async () => ({ok:true,body:Readable.from(['{}'])});
    assert.equal((await setup.action('test-model',{endpoint:config.modelEndpoint,name:'test'})).ok,false);
    const accounts = await setup.action('accounts',{});
    assert.equal(accounts.accounts[0].label,'账号鲸鱼');
    assert.equal(accounts.accounts[1].account,'wxid_鲸_abcd','UTF-8 account split across chunks survives exactly');
    const groups = await setup.action('groups',{account:'wxid_a_abcd',keyword:''});
    assert.equal(groups.groups[0].name,'中文群聊','UTF-8 group names split across chunks survive exactly');
    await setup.action('save',{account:'wxid_a_abcd',groupIds:['g@chatroom'],endpoint:config.modelEndpoint,name:'test'});
    assert.equal(config.botUserId,'wxid_a');
    assert.equal(JSON.parse(fs.readFileSync(path.join(root,'config.json'))).wechatBridge.botUserId,'wxid_a');
    assert.equal(JSON.parse(fs.readFileSync(path.join(root,'config.json'))).wechatBridge.enableAccessibility,undefined,'legacy saves do not enable accessibility');
    await assert.rejects(setup.action('save',{account:'wxid_a_abcd',groupIds:['g@chatroom'],endpoint:config.modelEndpoint,name:'test',enableAccessibility:'true'}),/布尔值/);
    await setup.action('save',{account:'wxid_a_abcd',groupIds:['g@chatroom'],endpoint:config.modelEndpoint,name:'test',enableAccessibility:true});
    assert.equal(setup.status().wechat.enableAccessibility,true);
    await assert.rejects(setup.action('save',{account:'wxid_a_abcd',groupIds:['g@chatroom'],endpoint:config.modelEndpoint,name:'test',randomEventsEnabled:'true'}),/布尔值/);
    await setup.action('save',{account:'wxid_a_abcd',groupIds:['g@chatroom'],endpoint:config.modelEndpoint,name:'test',randomEventsEnabled:false});
    assert.equal(setup.status().game.randomEventsEnabled,false);
    config.groupAllowlist.push('saved-unseen@chatroom');
    await assert.rejects(setup.action('save',{account:'wxid_a_abcd',groupIds:['g@chatroom'],endpoint:config.modelEndpoint,name:'new-model'}),/请确认/);
    assert(config.groupAllowlist.includes('saved-unseen@chatroom'),'saving a model cannot silently remove an unseen saved group');
    await setup.action('save',{account:'wxid_a_abcd',groupIds:['g@chatroom'],endpoint:config.modelEndpoint,name:'test',confirmRemovedGroupIds:['saved-unseen@chatroom']});
    assert.equal(JSON.parse(fs.readFileSync(path.join(root,'config.json'))).wechatBridge.enableAccessibility,true,'omitted option preserves saved consent');
    assert.equal(JSON.parse(fs.readFileSync(path.join(root,'config.json'))).randomEventsEnabled,false,'omitted event option preserves saved value');
    await setup.action('bridge',{action:'start'});
    const p = children.at(-1); const ready = p.options.env.GAL_BRIDGE_READY;
    assert.equal(p.options.stdio[0],'pipe');
    assert.equal(p.options.env.GAL_BRIDGE_MANAGED,'1');
    const progress = p.options.env.GAL_BRIDGE_PROGRESS;
    const update = values => fs.writeFileSync(progress,JSON.stringify({nonce:p.options.env.GAL_BRIDGE_NONCE,pid:p.pid,stage:'database',updatedAt:Date.now()/1000,...values}));
    update({nonce:'wrong'}); await delay(8); assert.equal(setup.status().bridge.stage,'config');
    update({pid:p.pid+1}); await delay(8); assert.equal(setup.status().bridge.stage,'config');
    update({updatedAt:0}); await delay(8); assert.equal(setup.status().bridge.stage,'config','stale progress is ignored');
    update({stage:'secret-key'}); await delay(8); assert.equal(setup.status().bridge.stage,'config','unknown stages cannot leak arbitrary text');
    update({error:'secret-key'}); await delay(8); assert.equal(setup.status().bridge.stage,'database');
    assert.equal(setup.status().bridge.state,'starting'); assert.equal(setup.status().bridge.error,undefined);
    assert.equal(typeof setup.status().bridge.elapsed,'number');
    fs.writeFileSync(ready,JSON.stringify({nonce:'wrong',pid:p.pid,updatedAt:Date.now()/1000}));
    await delay(15); assert.equal(setup.status().bridge.state,'starting');
    await setup.action('bridge',{action:'start'}); assert.equal(children.at(-1),p);
    fs.writeFileSync(ready,JSON.stringify({nonce:p.options.env.GAL_BRIDGE_NONCE,pid:p.pid,updatedAt:0}));
    await delay(8); assert.equal(setup.status().bridge.state,'starting','stale ready timestamps are rejected');
    fs.writeFileSync(ready,JSON.stringify({nonce:p.options.env.GAL_BRIDGE_NONCE,pid:p.pid,updatedAt:Date.now()/1000}));
    await delay(15); assert.equal(setup.status().bridge.state,'running');
    await assert.rejects(setup.action('bridge',{action:'stop',instance:'another-instance'}),/服务实例已更改/);
    assert.equal(p.stdin.writableEnded,false,'a stale launcher nonce cannot stop the current instance');
    await setup.action('bridge',{action:'stop',instance:setup.status().instance}); await delay(5);
    assert.equal(setup.status().bridge.state,'stopped'); assert(p.stdin.writableEnded); assert(!p.killed,'normal stop exits through pipe EOF');
    await setup.action('bridge',{action:'start'});
    const delayed = children.at(-1); delayed.delayClose = true;
    await setup.action('bridge',{action:'stop'});
    fs.writeFileSync(delayed.options.env.GAL_BRIDGE_READY, JSON.stringify({nonce:delayed.options.env.GAL_BRIDGE_NONCE,pid:delayed.pid,updatedAt:Date.now()/1000}));
    await delay(15); assert.notEqual(setup.status().bridge.state,'running');
    delayed.emit('close',1); assert.equal(setup.status().bridge.state,'stopped');
    await setup.action('bridge',{action:'start'}); const q=children.at(-1);
    q.stderr.write('桥接启动或运行失败：需要恰好一个可见的微信主窗口 secret-key'); q.emit('close',1);
    assert.equal(setup.status().bridge.error,'需要恰好一个可见的微信主窗口');
    await setup.action('bridge',{action:'start'}); const failed=children.at(-1);
    const uiaError = 'UIA未启用：请在设置中明确勾选微信无障碍兼容后保存并启动，或手动启用微信 UIA';
    fs.writeFileSync(failed.options.env.GAL_BRIDGE_PROGRESS,JSON.stringify({nonce:failed.options.env.GAL_BRIDGE_NONCE,pid:failed.pid,stage:'uia',updatedAt:Date.now()/1000,error:uiaError}));
    failed.emit('close',1); // Terminal update may land between supervisor polls.
    assert.equal(setup.status().bridge.error,uiaError); assert.equal(setup.status().bridge.state,'error');
    assert.equal(setup.status().bridge.stage,'uia'); assert.equal(failed.stdin.writableEnded,false,'already closed child must not be stopped again');
    await setup.action('bridge',{action:'start'}); const timeout=children.at(-1); timeout.ignoreEOF = true;
    fs.writeFileSync(timeout.options.env.GAL_BRIDGE_PROGRESS,JSON.stringify({nonce:timeout.options.env.GAL_BRIDGE_NONCE,pid:timeout.pid,stage:'imports',updatedAt:Date.now()/1000}));
    await delay(260);
    assert(timeout.killed); assert.match(setup.status().bridge.error,/桥接启动超时：导入 Windows\/UIA 依赖/);
    await setup.action('bridge',{action:'start'}); const closing=children.at(-1); setup.close(); await delay(5);
    assert(closing.stdin.writableEnded); assert.equal(setup.status().bridge.state,'stopped');
    console.log('setup mocked checks passed');
  } finally { global.fetch=original; setup.close(); fs.rmSync(root,{recursive:true,force:true}); }
})().catch(error => {console.error(error);process.exitCode=1;});

